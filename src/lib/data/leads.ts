export const LEADS: Lead[] = LEAD_SEEDS.map((seed) => ({ ...seed, id: nextId("lead") }))

function activity(leadId: string, type: LeadActivity["type"], description: string, timestamp: string): LeadActivity {
  return { id: `${leadId}_act_${Math.random().toString(36).slice(2, 8)}`, leadId, type, description, timestamp }
}

export const LEAD_ACTIVITIES: LeadActivity[] = LEADS.flatMap((lead) => {
  const items: LeadActivity[] = [activity(lead.id, "created", `Lead created from ${lead.source.platform}`, lead.createdAt)]
  if (lead.stage !== "new") {
    items.push(activity(lead.id, "whatsapp-started", "Started WhatsApp conversation", lead.createdAt))
  }
  if (lead.score > 0) {
    items.push(activity(lead.id, "score-updated", `Lead score set to ${lead.score}`, lead.updatedAt))
  }
  if (lead.callStatus) {
    items.push(activity(lead.id, "call-queued", "Queued for AI call", lead.updatedAt))
  }
  if (lead.meetingStatus) {
    items.push(activity(lead.id, "meeting-booked", "Meeting booked", lead.updatedAt))
  }
  return items
})
